<?php
declare(strict_types=1);

namespace Tests\Unit;

use App\Services\PreSettlementEngine;
use PHPUnit\Framework\TestCase;

/**
 * Pre-settlement / foreclosure math, verified to the paisa.
 *
 * Reference scenario used throughout (kept identical in the Python oracle):
 *
 *   Loan      : ₹1,00,000 @ 18% p.a. reducing, 12 monthly EMIs of ₹9,168.00
 *   Disbursed : 2026-01-01, first EMI 2026-02-01
 *   EMIs 1–3  : PAID on their due dates (2026-02-01, 03-01, 04-01)
 *   Settle on : 2026-05-10  (40 days after the 04-01 due date)
 *   Charge    : 3% of outstanding principal + 18% GST
 */
class PreSettlementEngineTest extends TestCase
{
    private PreSettlementEngine $engine;

    protected function setUp(): void
    {
        parent::setUp();
        $this->engine = new PreSettlementEngine();
    }

    /** 12-month schedule for ₹1,00,000 @ 18% reducing, EMI ₹9,168.00. */
    private function schedule(): array
    {
        // Principal/interest split per installment, computed independently.
        // Generated by ActuarialLoanEngine (₹1,00,000 @ 18%, 12 × 30-day steps)
        // and cross-verified field-by-field against oracle/settlement_oracle.py.
        $plan = [
            ['2026-01-31', '7668.00', '1500.00'],
            ['2026-03-02', '7783.02', '1384.98'],
            ['2026-04-01', '7899.77', '1268.23'],
            ['2026-05-01', '8018.26', '1149.74'],
            ['2026-05-31', '8138.54', '1029.46'],
            ['2026-06-30', '8260.61', '907.39'],
            ['2026-07-30', '8384.52', '783.48'],
            ['2026-08-29', '8510.29', '657.71'],
            ['2026-09-28', '8637.95', '530.05'],
            ['2026-10-28', '8767.51', '400.49'],
            ['2026-11-27', '8899.03', '268.97'],
            ['2026-12-27', '9032.50', '135.49'],
        ];

        $rows = [];
        foreach ($plan as $i => [$dueDate, $prin, $int]) {
            $paid = $i < 3 ? '9168.00' : '0.00';
            $rows[] = [
                'emi_no' => $i + 1,
                'due_date' => $dueDate,
                'emi_amount' => '9168.00',
                'principal_component' => $prin,
                'interest_component' => $int,
                'paid_amount' => $paid,
                'paid_date' => $i < 3 ? $dueDate : null,
            ];
        }

        return $rows;
    }

    /** Same schedule but nobody has paid a single EMI. */
    private function unpaidSchedule(): array
    {
        return array_map(static function (array $row): array {
            $row['paid_amount'] = '0.00';
            $row['paid_date'] = null;

            return $row;
        }, $this->schedule());
    }

    private function baseQuote(array $over = []): array
    {
        return $this->engine->quote($over + [
            'loan_id' => 'LN-TEST-001',
            'plan_amount' => '100000.00',
            'interest_rate_pa' => '18.00',
            'annual_days' => '365',
            'disbursement_date' => '2026-01-01',
            'settlement_date' => '2026-05-10',
            'installment_amounts' => $this->schedule(),
            'foreclosure_charge_pct' => '3.00',
            'foreclosure_charge_gst_pct' => '18.00',
            'penalty_due' => '0.00',
        ]);
    }

    /** Principal outstanding after 3 paid EMIs = 100000 − (7668 + 7783.02 + 7899.77). */
    public function test_principal_outstanding_is_exact(): void
    {
        $q = $this->baseQuote();
        $this->assertSame('76649.21', $q['principal']['unpaid']);
        $this->assertSame('23350.79', $q['principal']['paid_till_date']);
    }

    /** Broken period = 2026-04-01 → 2026-05-10 = 39 days (not 40). */
    public function test_broken_period_days(): void
    {
        $q = $this->baseQuote();
        $this->assertSame(39, $q['interest']['broken_period_days']);
    }

    /**
     * Broken-period interest = 76,649.21 × 18% / 365 × 39 = ₹1,474.18.
     * Cross-checked with Python Decimal. The old formula charged ZERO here.
     */
    public function test_broken_period_interest_is_charged(): void
    {
        $q = $this->baseQuote();
        $this->assertSame('1474.18', $q['interest']['broken_period_interest'],
            'Broken-period interest must be charged — the old code gave this away.');
    }

    /**
     * Future (not-yet-accrued) interest must be waived, not collected.
     *
     * As at 2026-05-10 only the 05-01 EMI has fallen due but is unpaid, so its
     * interest (1,149.74) is accrued and collectible. 06-01 onwards is still
     * in the future — 06-01 is AFTER 05-10 — so it is waived entirely.
     */
    public function test_future_interest_is_waived_not_collected(): void
    {
        $q = $this->baseQuote();
        $this->assertSame('1149.74', $q['interest']['unpaid_scheduled']);
        $this->assertGreaterThan(0, (float) $q['interest']['future_waived_off']);
        $this->assertSame(
            '2623.92',
            $q['interest']['payable'],
            'payable = accrued scheduled 1,149.74 + broken period 1,474.18'
        );
    }

    /** Total = principal + accrued interest + 3% charge + 18% GST on that charge. */
    public function test_total_payable_breakdown(): void
    {
        $q = $this->baseQuote();

        $prin = $q['principal']['payable'];
        $int = $q['interest']['payable'];
        $charge = $q['charges']['net_charge'];
        $gst = $q['charges']['gst_payable'];

        $expectedCharge = \App\Services\BcMathCalculator::percentageOf('76649.21', '3.00');
        $expectedGst = \App\Services\BcMathCalculator::percentageOf($expectedCharge, '18.00');

        $this->assertSame($expectedCharge, $charge);
        $this->assertSame($expectedGst, $gst);
        $this->assertSame('2299.48', $charge);
        $this->assertSame('413.91', $gst);

        $sum = \App\Services\BcMathCalculator::add(
            \App\Services\BcMathCalculator::add($prin, $int, 2),
            \App\Services\BcMathCalculator::add($charge, $gst, 2),
            2
        );
        $this->assertSame($sum, $q['total_payable']);
    }

    /** The voucher must balance to the paisa — or the engine must refuse to quote. */
    public function test_voucher_balances(): void
    {
        $q = $this->baseQuote();
        $this->assertTrue($q['voucher']['balanced']);
        $this->assertSame($q['voucher']['debit_total'], $q['voucher']['credit_total']);

        $dr = '0.00';
        foreach ($q['voucher']['debits'] as $row) {
            $dr = \App\Services\BcMathCalculator::add($dr, $row['amount'], 2);
        }
        $cr = '0.00';
        foreach ($q['voucher']['credits'] as $row) {
            $cr = \App\Services\BcMathCalculator::add($cr, $row['amount'], 2);
        }
        $this->assertSame($dr, $cr);
        $this->assertSame($dr, $q['voucher']['debit_total']);
    }

    /** DPD must be measured from the oldest unpaid due date. */
    public function test_dpd_and_classification(): void
    {
        $q = $this->baseQuote();
        // 04-01 is paid, so the oldest UNPAID due date is 2026-05-01 — still
        // in the future relative to 2026-05-10? No: 05-01 < 05-10, so DPD = 9.
        $this->assertSame(9, $q['risk']['dpd']);
        $this->assertSame('SMA-0', $q['risk']['asset_class']);
        $this->assertFalse($q['risk']['is_npa']);
    }

    /** RBI thresholds: 90 days is still SMA-2, 91 is NPA. */
    public function test_npa_threshold_is_exactly_90_days(): void
    {
        $e = new PreSettlementEngine();
        $this->assertFalse($e->classify(90)['is_npa'], 'Day 90 is SMA-2, not yet NPA');
        $this->assertSame('SMA-2', $e->classify(90)['asset_class']);
        $this->assertTrue($e->classify(91)['is_npa'], 'Day 91 is NPA');
        $this->assertSame('SUB-STANDARD', $e->classify(91)['asset_class']);
        // RBI IRACP: sub-standard = 10% of outstanding + 10% extra on unsecured
        // = 20% for a fully unsecured JLG loan.
        $this->assertSame('20.00', $e->classify(91)['provision_rate_pct']);
    }

    /** Doubtful kicks in after 18 months in NPA = 90 + 540 = 630 DPD.
     *  DOUBTFUL-1 starts at the next 30-day boundary: DPD 660. */
    public function test_doubtful_threshold_after_18_months_of_npa(): void
    {
        $e = new PreSettlementEngine();
        // 540 days = 18 months from disbursement, but only 450 days in NPA.
        $this->assertSame('SUB-STANDARD', $e->classify(540)['asset_class']);
        $this->assertSame('SUB-STANDARD', $e->classify(630)['asset_class']);
        // 630 days = 90 (grace) + 540 (18 months in NPA). Still sub-standard.
        $this->assertSame('SUB-STANDARD', $e->classify(631)['asset_class']);
        // 660 days = 90 + 570 (19 months in NPA) → DOUBTFUL-1.
        $this->assertSame('DOUBTFUL-1', $e->classify(660)['asset_class']);
        $this->assertSame('100.00', $e->classify(660)['provision_rate_pct']);
    }

    /** A 100% waiver must produce a zero-payable settlement that still balances. */
    public function test_full_principal_waiver_still_balances(): void
    {
        $q = $this->engine->quote([
            'loan_id' => 'LN-WO-1',
            'plan_amount' => '100000.00',
            'interest_rate_pa' => '18.00',
            'disbursement_date' => '2026-01-01',
            'settlement_date' => '2026-05-10',
            'installment_amounts' => $this->schedule(),
            'foreclosure_charge_pct' => '0.00',
            'foreclosure_charge_flat' => '0.00',
            'penalty_due' => '0.00',
            'waiver' => ['principal' => '76649.21', 'interest' => '999999.00', 'reason' => 'Death of borrower — write-off'],
            'write_off' => true,
        ]);

        $this->assertSame('0.00', $q['principal']['payable']);
        $this->assertSame('0.00', $q['total_payable']);
        $this->assertTrue($q['voucher']['balanced']);
        $this->assertSame($q['voucher']['debit_total'], $q['voucher']['credit_total']);
    }

    /** Waiving a charge must also remove the GST on it — never tax money nobody paid. */
    public function test_charge_waiver_kills_the_gst(): void
    {
        $q = $this->engine->quote([
            'loan_id' => 'LN-WC-1',
            'plan_amount' => '100000.00',
            'interest_rate_pa' => '18.00',
            'disbursement_date' => '2026-01-01',
            'settlement_date' => '2026-05-10',
            'installment_amounts' => $this->schedule(),
            'foreclosure_charge_pct' => '3.00',
            'foreclosure_charge_gst_pct' => '18.00',
            'waiver' => ['charge' => '2299.48'],
        ]);
        $this->assertSame('0.00', $q['charges']['payable']);
        $this->assertSame('0.00', $q['charges']['gst_payable']);
    }

    /**
     * Settlement on the disbursement date itself: no broken period, and since
     * nobody has paid anything the WHOLE principal is outstanding.
     */
    public function test_settlement_on_day_zero(): void
    {
        $q = $this->engine->quote([
            'loan_id' => 'LN-D0',
            'plan_amount' => '100000.00',
            'interest_rate_pa' => '18.00',
            'disbursement_date' => '2026-01-01',
            'settlement_date' => '2026-01-01',
            'installment_amounts' => $this->unpaidSchedule(),
            'foreclosure_charge_pct' => '0.00',
            'foreclosure_charge_flat' => '0.00',
        ]);
        $this->assertSame(0, $q['interest']['broken_period_days']);
        $this->assertSame('0.00', $q['interest']['broken_period_interest']);
        $this->assertSame('100000.00', $q['principal']['payable'],
            'No EMIs paid yet ⇒ entire plan_amount is outstanding');
        $this->assertTrue($q['voucher']['balanced']);
    }

    /** Every rupee of paise must survive: 1-paisa principal. */
    public function test_one_paisa_loan(): void
    {
        $q = $this->engine->quote([
            'loan_id' => 'LN-PAISA',
            'plan_amount' => '0.01',
            'interest_rate_pa' => '18.00',
            'disbursement_date' => '2026-01-01',
            'settlement_date' => '2026-02-01',
            'installment_amounts' => [[
                'emi_no' => 1, 'due_date' => '2026-02-01', 'emi_amount' => '0.01',
                'principal_component' => '0.01', 'interest_component' => '0.00',
                'paid_amount' => '0.00', 'paid_date' => null,
            ]],
            'foreclosure_charge_pct' => '0.00',
            'foreclosure_charge_flat' => '0.00',
        ]);
        $this->assertSame('0.01', $q['principal']['payable']);
        $this->assertTrue($q['voucher']['balanced']);
    }
}
