<?php
declare(strict_types=1);

namespace Tests\Unit;

use App\Services\ActuarialLoanEngine;
use App\Services\PreSettlementEngine;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;

/**
 * Cross-language parity: PHP engine vs the independent Python oracle.
 *
 * The oracle (oracle/settlement_oracle.py) reprojects the same loan using a
 * completely different code path — a day-by-day accrual walk rather than an
 * aggregate formula. If both agree to the paisa across a randomised matrix,
 * a shared implementation bug is essentially ruled out.
 *
 * The oracle JSON is generated by tools/gen_oracle_cases.py and committed, so
 * this test runs with no Python dependency in CI.
 */
class PreSettlementOracleParityTest extends TestCase
{
    private function oracleCases(): array
    {
        $path = __DIR__.'/../../tests/fixtures/settlement_oracle_cases.json';
        if (! file_exists($path)) {
            $this->markTestSkipped('Oracle fixture missing — run tools/gen_oracle_cases.py');
        }
        $json = json_decode((string) file_get_contents($path), true);

        return $json['cases'] ?? [];
    }

    public function test_oracle_fixture_exists_and_has_cases(): void
    {
        $cases = $this->oracleCases();
        $this->assertNotEmpty($cases, 'Oracle must supply at least one case');
    }

    /** Every oracle case must be reproduced exactly by the PHP engine. */
    public function test_php_matches_python_oracle_field_by_field(): void
    {
        $cases = $this->oracleCases();
        if ($cases === []) {
            $this->markTestSkipped('no cases');
        }

        $checked = 0;
        foreach ($cases as $case) {
            $sched = (new ActuarialLoanEngine())->calculateEmiBreakdown([
                'plan_amount' => $case['plan_amount'],
                'interest_rate_pa' => $case['interest_rate_pa'],
                'tenure_emis' => $case['tenure_emis'],
                'recovery_type' => 'MONTHLY',
                'interest_type' => 'REDUCING',
                'start_date' => $case['start_date'],
                'file_charge' => '0.00',
                'pf_amount' => '0.00',
                'insurance_amount' => '0.00',
                'gst_include' => 'NO',
            ]);

            $rows = [];
            foreach ($sched['schedule'] as $i => $s) {
                $paid = $i < (int) $case['paid_emis'];
                $rows[] = [
                    'emi_no' => $s['emi_no'],
                    'due_date' => $s['due_date'],
                    'emi_amount' => $s['emi_amount'],
                    'principal_component' => $s['principal_component'],
                    'interest_component' => $s['interest_component'],
                    'paid_amount' => $paid ? $s['emi_amount'] : '0.00',
                    'paid_date' => $paid ? $s['due_date'] : null,
                ];
            }

            $q = (new PreSettlementEngine())->quote([
                'plan_amount' => $case['plan_amount'],
                'interest_rate_pa' => $case['interest_rate_pa'],
                'annual_days' => '365',
                'disbursement_date' => $case['start_date'],
                'settlement_date' => $case['settlement_date'],
                'installment_amounts' => $rows,
                'foreclosure_charge_pct' => $case['charge_pct'],
                'foreclosure_charge_gst_pct' => '18.00',
                'penalty_due' => '0.00',
            ]);

            $actual = [
                'principal_outstanding' => $q['principal']['unpaid'],
                'broken_period_days' => (string) $q['interest']['broken_period_days'],
                'broken_period_interest' => $q['interest']['broken_period_interest'],
                'accrued_scheduled_interest' => $q['interest']['unpaid_scheduled'],
                'interest_due' => $q['interest']['payable'],
                'foreclosure_charge' => $q['charges']['net_charge'],
                'gst_on_charge' => $q['charges']['gst_payable'],
                'total_payable' => $q['total_payable'],
            ];

            foreach ($case['expected'] as $key => $want) {
                if (! array_key_exists($key, $actual)) {
                    continue;
                }
                $this->assertSame(
                    (string) $want,
                    $actual[$key],
                    "Case '{$case['name']}' field '{$key}': PHP and Python disagree"
                );
                $checked++;
            }

            // Whatever the numbers, the books must balance.
            $this->assertTrue($q['voucher']['balanced'], "Case '{$case['name']}' voucher unbalanced");
            $this->assertSame($q['voucher']['debit_total'], $q['voucher']['credit_total']);
        }

        $this->assertGreaterThan(30, $checked, 'Expected a broad field sweep');
    }
}
